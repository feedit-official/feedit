_WS = re.compile(r"\s+")


def _norm(s) -> str:
    return _WS.sub(" ", unicodedata.normalize("NFC", str(s or "")).strip().lower())


def _any_in(hay: str, words) -> str | None:
    for w in words:
        if w in hay:
            return w
    return None


def judge(name: str = "", category_path: str = "", *,
          site_tags=None) -> tuple[bool, str]:
    """담을 것인가. `(담는다, 이유)` 를 돌려준다.

    이유는 사람이 읽는 한 줄이다. 화면과 기록에 그대로 쓴다.
    """
    cat = _norm(category_path)
    if site_tags:
        cat += " " + _norm(" ".join(str(t) for t in site_tags))

    if cat:
        hit = _any_in(cat, DROP_CATEGORY)
        if hit:
            # 분류에 '가방'과 '상의'가 같이 있으면 옷 쪽을 믿는다.
            # (유즈드처럼 여러 단계가 한 줄에 붙는 경우가 있다.)
            keep_hit = _any_in(cat, KEEP_CATEGORY)
            if not keep_hit:
                return False, f"옷이 아닌 분류입니다 — '{hit}'"
        if _any_in(cat, KEEP_CATEGORY):
            return True, ""

    nm = _norm(name)
    if not nm:
        # 이름도 분류도 없으면 아직 모르는 것이다. 버리지 않는다.
        return True, ""

    if _any_in(nm, NAME_KEEP):
        return True, ""
    hit = _any_in(nm, NAME_DROP)
    if hit:
        return False, f"옷이 아닌 상품으로 보입니다 — 이름에 '{hit}'"
    return True, ""


def keep(name: str = "", category_path: str = "", **kw) -> bool:
    return judge(name, category_path, **kw)[0]
